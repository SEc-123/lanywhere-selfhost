static bool chinese_enabled;
static bool spanish_enabled;

void ui_set_language(bool chinese, bool spanish)
{
    chinese_enabled = chinese;
    spanish_enabled = spanish && !chinese;
}

bool ui_chinese(void) { return chinese_enabled; }
bool ui_spanish(void) { return spanish_enabled; }

const char *ui_text(const char *english)
{
    if (!chinese_enabled || !english) return english;
    for (size_t i = 0; i < sizeof(translations) / sizeof(translations[0]); ++i)
        if (strcmp(english, translations[i].en) == 0) return translations[i].zh;
    return english;
}

const char *ui_tr(const char *spanish, const char *english)
{
    return chinese_enabled ? ui_text(english) : (spanish_enabled && spanish) ? spanish : english;
}
